/* PROTOTYPES */

/**
 * Allocate a block of main memory for a process's space.
 *
 * \return the address of a block or `0` if no block is available.
 */
address_t mm_allocate ();

/**
 * Free an allocated block of main memory, reclaiming it for later re-use.
 *
 * \param base  The base address of a block of memory previously allocated by `mm_allocate()`.
 */
void mm_deallocate (address_t base);
