/* =============================================================================================================================== */
/* TYPES */

typedef uint32_t address_t;
typedef uint32_t word_t;

#if !defined(NULL)
#define NULL ((void*)0)
#endif /* NULL */

// struct is just data members
// dt_entry_s* means the pointer points to a triplet
typedef struct dt_entry {
  word_t    type;
  address_t base;
  address_t limit;
} dt_entry_s; // dt_entry_s is a shorthand for "struct dt_entry" so it's easier for us to call

typedef struct DMA_portal {
  address_t src;
  address_t dst;
  word_t    length;
} DMA_portal_s;

typedef struct process {
  struct process* next;
  struct process* prev;
  address_t       base;
  address_t       limit;
  word_t          epc;
  word_t          sp;
  word_t          rom_number;
  word_t          id;
} process_s;
