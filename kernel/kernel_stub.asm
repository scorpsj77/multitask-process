### Procedure: syscall_handler
### Return value:
###   <does not return>

syscall_handler:

	## Preserve the epc & sp, then reset the stack for the kernel.
	sw		sp,		preserved_sp,	t6
	csrr		sp,		epc
	sw		sp,		preserved_epc, 	t6
	lw		sp,		kernel_limit

	## Do the management.
	call		do_syscall
